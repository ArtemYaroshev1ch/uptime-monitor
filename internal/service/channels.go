package service

import (
	"cmp"
	"context"
	"crypto/rand"
	"fmt"
	"slices"
	"strings"
	"time"

	"github.com/google/uuid"

	"github.com/artemyaroshev1ch/uptime-monitor/internal/domain"
	"github.com/artemyaroshev1ch/uptime-monitor/internal/platform/clock"
)

// MaxChannelsPerUser bounds the channels of one user. Every incident is
// fanned out to all of them, so the limit also bounds the deliveries one
// incident causes.
const MaxChannelsPerUser = 10

// testSendTimeout bounds a test notification, sent while the client waits.
const testSendTimeout = 10 * time.Second

// ChannelRepository stores notification channels. Every method is scoped to
// the owner; another user's channel is domain.ErrNotFound.
type ChannelRepository interface {
	// Create returns domain.ErrLimitExceeded if the user has limit channels.
	Create(ctx context.Context, userID uuid.UUID, ch domain.Channel, limit int) (domain.Channel, error)
	Get(ctx context.Context, userID, id uuid.UUID) (domain.Channel, error)
	List(ctx context.Context, userID uuid.UUID, limit, offset int) ([]domain.Channel, int, error)
	// Update runs fn on the locked channel and saves it; an error from fn
	// aborts the update.
	Update(ctx context.Context, userID, id uuid.UUID, fn func(*domain.Channel) error) (domain.Channel, error)
	Delete(ctx context.Context, userID, id uuid.UUID) error
}

// Sender delivers a message to a channel (notifier.Dispatcher). Its error
// texts contain no secrets and may be shown to the user.
type Sender interface {
	Send(ctx context.Context, ch domain.Channel, msg domain.Message) error
}

// ChannelConfigPatch is the config part of ChannelPatch.
type ChannelConfigPatch struct {
	ChatID Optional[string] `json:"chat_id"`
	URL    Optional[string] `json:"url"`
}

// ChannelPatch is the input of create and update. Type is required on
// create and cannot be changed. On update, config fields that are absent
// keep their values. The webhook secret is generated by the server and is
// not part of the input.
type ChannelPatch struct {
	Type     Optional[string]    `json:"type"`
	Name     Optional[string]    `json:"name"`
	Config   *ChannelConfigPatch `json:"config"`
	IsActive Optional[bool]      `json:"is_active"`
}

// ChannelPage is one page of channels.
type ChannelPage struct {
	Items []domain.Channel
	Total int
}

// TestResult is the outcome of a test notification.
type TestResult struct {
	Delivered bool
	// Error says why the delivery failed. It contains no secrets.
	Error string
}

// Channels manages the notification channels of a user.
type Channels struct {
	repo   ChannelRepository
	urls   URLPolicy
	sender Sender
	clock  clock.Clock
}

// NewChannels returns the Channels service. urls validates webhook URLs
// like monitor URLs; sender delivers test notifications.
func NewChannels(repo ChannelRepository, urls URLPolicy, sender Sender, clk clock.Clock) *Channels {
	return &Channels{repo: repo, urls: urls, sender: sender, clock: clk}
}

// Create adds a channel. For a webhook it generates the signing secret,
// which the returned channel carries; this is the only time the API shows
// it. Errors: *domain.ValidationError, domain.ErrLimitExceeded.
func (s *Channels) Create(ctx context.Context, userID uuid.UUID, p ChannelPatch) (domain.Channel, error) {
	ch := domain.Channel{IsActive: true}
	var details []domain.FieldError
	switch {
	case !p.Type.Set || p.Type.Null:
		details = append(details, domain.FieldError{Field: "type", Issue: "is required"})
	case p.Type.Value != string(domain.ChannelTelegram) && p.Type.Value != string(domain.ChannelWebhook):
		details = append(details, domain.FieldError{Field: "type", Issue: "must be one of: telegram webhook"})
	default:
		ch.Type = domain.ChannelType(p.Type.Value)
	}
	if !p.Name.Set {
		details = append(details, domain.FieldError{Field: "name", Issue: "is required"})
	}
	if p.Config == nil && ch.Type != "" {
		details = append(details, domain.FieldError{Field: "config", Issue: "is required"})
	}
	if err := s.apply(&ch, p, details); err != nil {
		return domain.Channel{}, err
	}
	if ch.Type == domain.ChannelWebhook {
		// 128 random bits, base32 (crypto/rand.Text): enough to make the
		// HMAC unforgeable, and safe to paste into any config file.
		ch.Config.Secret = rand.Text()
	}

	out, err := s.repo.Create(ctx, userID, ch, MaxChannelsPerUser)
	if err != nil {
		return domain.Channel{}, fmt.Errorf("create channel: %w", err)
	}
	return out, nil
}

// Get returns one of the user's channels or domain.ErrNotFound.
func (s *Channels) Get(ctx context.Context, userID, id uuid.UUID) (domain.Channel, error) {
	ch, err := s.repo.Get(ctx, userID, id)
	if err != nil {
		return domain.Channel{}, fmt.Errorf("get channel: %w", err)
	}
	return ch, nil
}

// List returns a page of the user's channels, newest first.
func (s *Channels) List(ctx context.Context, userID uuid.UUID, limit, offset int) (ChannelPage, error) {
	items, total, err := s.repo.List(ctx, userID, limit, offset)
	if err != nil {
		return ChannelPage{}, fmt.Errorf("list channels: %w", err)
	}
	return ChannelPage{Items: items, Total: total}, nil
}

// Update changes the fields present in p. Errors: *domain.ValidationError,
// domain.ErrNotFound.
func (s *Channels) Update(ctx context.Context, userID, id uuid.UUID, p ChannelPatch) (domain.Channel, error) {
	ch, err := s.repo.Update(ctx, userID, id, func(ch *domain.Channel) error {
		var details []domain.FieldError
		if p.Type.Set {
			details = append(details, domain.FieldError{Field: "type", Issue: "cannot be changed"})
		}
		return s.apply(ch, p, details)
	})
	if err != nil {
		return domain.Channel{}, fmt.Errorf("update channel: %w", err)
	}
	return ch, nil
}

// Delete removes one of the user's channels and its pending notifications.
func (s *Channels) Delete(ctx context.Context, userID, id uuid.UUID) error {
	if err := s.repo.Delete(ctx, userID, id); err != nil {
		return fmt.Errorf("delete channel: %w", err)
	}
	return nil
}

// Test sends a test notification to one of the user's channels right away,
// bypassing the outbox, so the user sees at once whether the channel works.
// A failed delivery is a result, not an error: the request itself
// succeeded. It works for disabled channels too, so a channel can be
// checked before it is enabled.
func (s *Channels) Test(ctx context.Context, userID, id uuid.UUID) (TestResult, error) {
	ch, err := s.repo.Get(ctx, userID, id)
	if err != nil {
		return TestResult{}, fmt.Errorf("test channel: %w", err)
	}
	ctx, cancel := context.WithTimeout(ctx, testSendTimeout)
	defer cancel()
	msg := domain.Message{Event: domain.EventTest, ChannelName: ch.Name, At: s.clock.Now()}
	if err := s.sender.Send(ctx, ch, msg); err != nil {
		return TestResult{Error: err.Error()}, nil
	}
	return TestResult{Delivered: true}, nil
}

// apply writes the fields present in p into ch and validates the result,
// reporting all problems (including the given ones) sorted by field.
func (s *Channels) apply(ch *domain.Channel, p ChannelPatch, details []domain.FieldError) error {
	if p.Name.Set {
		name := strings.TrimSpace(p.Name.Value)
		switch {
		case p.Name.Null || name == "":
			details = append(details, domain.FieldError{Field: "name", Issue: "is required"})
		case len([]rune(name)) > 100:
			details = append(details, domain.FieldError{Field: "name", Issue: "must be at most 100 characters"})
		default:
			ch.Name = name
		}
	}
	if p.IsActive.Set {
		if p.IsActive.Null {
			details = append(details, domain.FieldError{Field: "is_active", Issue: "must not be null"})
		} else {
			ch.IsActive = p.IsActive.Value
		}
	}
	if p.Config != nil && ch.Type != "" {
		details = append(details, s.applyConfig(ch, *p.Config)...)
	}

	if len(details) == 0 {
		return nil
	}
	slices.SortStableFunc(details, func(a, b domain.FieldError) int { return cmp.Compare(a.Field, b.Field) })
	return &domain.ValidationError{Details: details}
}

// applyConfig applies the config fields of ch.Type and rejects the fields of
// the other type.
func (s *Channels) applyConfig(ch *domain.Channel, c ChannelConfigPatch) []domain.FieldError {
	var details []domain.FieldError
	notFor := func(field string, set bool) {
		if set {
			details = append(details, domain.FieldError{Field: "config." + field, Issue: "is not used by " + string(ch.Type) + " channels"})
		}
	}

	switch ch.Type {
	case domain.ChannelTelegram:
		notFor("url", c.URL.Set)
		if c.ChatID.Set {
			ch.Config.ChatID = strings.TrimSpace(c.ChatID.Value)
		}
		switch {
		case c.ChatID.Null || ch.Config.ChatID == "":
			details = append(details, domain.FieldError{Field: "config.chat_id", Issue: "is required"})
		case len(ch.Config.ChatID) > 100 || strings.ContainsAny(ch.Config.ChatID, " \t\r\n"):
			details = append(details, domain.FieldError{Field: "config.chat_id", Issue: "must be a chat ID or @username"})
		}
	case domain.ChannelWebhook:
		notFor("chat_id", c.ChatID.Set)
		if !c.URL.Set {
			if ch.Config.URL == "" {
				details = append(details, domain.FieldError{Field: "config.url", Issue: "is required"})
			}
			break
		}
		url := strings.TrimSpace(c.URL.Value)
		if c.URL.Null || url == "" {
			details = append(details, domain.FieldError{Field: "config.url", Issue: "is required"})
			break
		}
		if err := s.urls.ValidateURL(url); err != nil {
			details = append(details, domain.FieldError{Field: "config.url", Issue: err.Error()})
			break
		}
		ch.Config.URL = url
	}
	return details
}
